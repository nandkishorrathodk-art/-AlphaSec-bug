"""Payload knowledge base for prompt-injection research.

Technique templates are parameterised with ``{placeholders}`` that the
generator expands.  Every template documents *why* it works so the chatbot
can explain its strategy instead of blindly spraying text.
"""

from __future__ import annotations

import base64
from dataclasses import dataclass, field
from typing import Iterable


@dataclass(frozen=True, slots=True)
class Technique:
    """A single attack technique with optionally parameterised templates."""

    id: str
    name: str
    category: str
    description: str
    when_to_use: str
    templates: tuple[str, ...]
    # Placeholder -> example value, used by ``expand`` and surfaced in chat.
    example_placeholders: dict[str, str] = field(default_factory=dict)


