def get_technique(tech_id: str) -> Technique | None:
    for tech in TECHNIQUES:
        if tech.id == tech_id:
            return tech
    return None


def expand(template: str, placeholders: dict[str, str] | None = None) -> str:
    """Expand a template using placeholders, defaulting each missing slot to a sane example value."""
    scope = {**_DEFAULT_PLACEHOLDERS, **(placeholders or {})}
    try:
        return template.format(**scope)
    except KeyError as exc:  # pragma: no cover - defensive
        token = str(exc).strip("'")
        return template.replace("{" + token + "}", "").format(**scope)


def generate(tech_ids: Iterable[str] | None = None, categories: Iterable[str] | None = None,
             extra: dict[str, str] | None = None, limit: int | None = None) -> list[tuple[Technique, str]]:
    """Yield (technique, expanded_payload) pairs across the selected techniques/categories."""
    techs = [t for t in TECHNIQUES
             if (tech_ids is None or t.id in set(tech_ids))
             and (categories is None or t.category in set(categories))]
    out: list[tuple[Technique, str]] = []
    for tech in techs:
        for template in tech.templates:
            out.append((tech, expand(template, extra)))
    if limit:
        out = out[:limit]
    return out


def strategy_chain(tech_ids: list[str], goal: str | None = None) -> list[tuple[Technique, str]]:
    """Turn an ordered list of technique ids into a coherent multi-step strategy."""
    extra = {"goal": goal} if goal else None
    chain: list[tuple[Technique, str]] = []
    for tid in tech_ids:
        tech = get_technique(tid)
        if tech:
            chain.append((tech, expand(tech.templates[0], extra)))
    return chain